-- ZADANIE 1C
CREATE INDEX FIGURY_SIDX
ON FIGURY(KSZTALT)
INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2;

-- ZADANIE 1D
SELECT ID
FROM FIGURY
WHERE SDO_FILTER(KSZTALT, MDSYS.SDO_GEOMETRY( 2001, NULL, MDSYS.SDO_POINT_TYPE(3,3,NULL), NULL, NULL)) = 'TRUE';

--SDO_FILTER wykonuje wstępne sprawdzanie przestrzenne. Nie analizuje dokładnego kształtu figur, 
--tylko ich prostokąty ograniczające (Minimum Bounding Rectangle).

-- ZADANIE 1E
SELECT ID
FROM FIGURY
WHERE SDO_RELATE(KSZTALT, MDSYS.SDO_GEOMETRY( 2001, NULL, MDSYS.SDO_POINT_TYPE(3,3,NULL), NULL, NULL), 'mask=ANYINTERACT') = 'TRUE';

-- ZADANIE 2A
SELECT M.CITY_NAME AS MIASTO, SDO_NN_DISTANCE(1) AS ODL
FROM MAJOR_CITIES M
WHERE SDO_NN(
    M.GEOM,
    (SELECT W.GEOM
     FROM MAJOR_CITIES W
     WHERE W.CITY_NAME = 'Warsaw'),
    'sdo_num_res=10 unit=KM',
    1) = 'TRUE'
AND M.CITY_NAME <> 'Warsaw';

-- ZADANIE 2B
SELECT M.CITY_NAME AS MIASTO
FROM MAJOR_CITIES M
WHERE SDO_WITHIN_DISTANCE(
    M.GEOM,
    (SELECT W.GEOM
     FROM MAJOR_CITIES W
     WHERE W.CITY_NAME = 'Warsaw'),
    'distance=100 unit=KM') = 'TRUE'
AND M.CITY_NAME <> 'Warsaw';

-- ZADANIE 2C
SELECT P.CNTRY_NAME AS KRAJ, M.CITY_NAME AS MIASTO
FROM COUNTRY_BOUNDARIES P, MAJOR_CITIES M
WHERE P.CNTRY_NAME = 'Slovakia'
AND SDO_RELATE(M.GEOM, P.GEOM, 'mask=INSIDE') = 'TRUE';
    
-- ZADANIE 2D
SELECT P.CNTRY_NAME AS PANSTWO,
    SDO_GEOM.SDO_DISTANCE(P.GEOM, PL.GEOM, 0.005, 'unit=KM') AS ODL
FROM COUNTRY_BOUNDARIES P, COUNTRY_BOUNDARIES PL
WHERE PL.CNTRY_NAME = 'Poland'
AND P.CNTRY_NAME <> 'Poland'
AND SDO_RELATE(P.GEOM, PL.GEOM, 'mask=ANYINTERACT') <> 'TRUE'
ORDER BY ODL;

-- ZADANIE 3A
SELECT P.CNTRY_NAME,
    SDO_GEOM.SDO_LENGTH(SDO_GEOM.SDO_INTERSECTION(P.GEOM, PL.GEOM, 0.005), 0.005, 'unit=KM') AS ODLEGLOSC
FROM COUNTRY_BOUNDARIES P, COUNTRY_BOUNDARIES PL
WHERE PL.CNTRY_NAME = 'Poland'
  AND P.CNTRY_NAME <> 'Poland'
  AND SDO_RELATE(P.GEOM, PL.GEOM, 'mask=TOUCH') = 'TRUE';
  
-- ZADANIE 3B
SELECT CNTRY_NAME
FROM COUNTRY_BOUNDARIES
ORDER BY SDO_GEOM.SDO_AREA(GEOM, 0.005, 'unit=SQ_KM') DESC
FETCH FIRST 1 ROW ONLY;

-- ZADANIE 3C
SELECT SDO_GEOM.SDO_AREA(SDO_AGGR_MBR(M.GEOM), 0.005, 'unit=SQ_KM') AS SQ_KM
FROM MAJOR_CITIES M
WHERE M.CITY_NAME IN ('Warsaw', 'Lodz');

-- ZADANIE 3D
SELECT SDO_GEOM.SDO_UNION(P.GEOM, M.GEOM, 0.005).SDO_GTYPE AS GTYPE
FROM COUNTRY_BOUNDARIES P, MAJOR_CITIES M
WHERE P.CNTRY_NAME = 'Poland' AND M.CITY_NAME = 'Prague';

-- ZADANIE 3E
SELECT M.CITY_NAME, P.CNTRY_NAME
FROM MAJOR_CITIES M, COUNTRY_BOUNDARIES P
WHERE SDO_RELATE(M.GEOM, P.GEOM, 'mask=INSIDE') = 'TRUE'
ORDER BY SDO_GEOM.SDO_DISTANCE(M.GEOM, SDO_GEOM.SDO_CENTROID(P.GEOM, 0.005), 0.005, 'unit=KM')
FETCH FIRST 1 ROW ONLY;

-- ZADANIE 3F
SELECT R.NAME,
    SUM(SDO_GEOM.SDO_LENGTH(SDO_GEOM.SDO_INTERSECTION(R.GEOM, P.GEOM, 0.005 ), 0.005, 'unit=KM')) AS DLUGOSC
FROM RIVERS R, COUNTRY_BOUNDARIES P
WHERE P.CNTRY_NAME = 'Poland'
AND SDO_RELATE(R.GEOM, P.GEOM, 'mask=ANYINTERACT') = 'TRUE'
GROUP BY R.NAME;