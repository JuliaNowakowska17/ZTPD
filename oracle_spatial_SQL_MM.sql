-- ZADANIE 3A
CREATE TABLE MYST_COUNTRY_BOUNDARIES(
FIPS_CNTRY VARCHAR2(2),
CNTRY_NAME VARCHAR2(40),
STGEOM MDSYS.ST_MULTIPOLYGON);

-- ZADANIE 3B
INSERT INTO MYST_COUNTRY_BOUNDARIES(FIPS_CNTRY, CNTRY_NAME, STGEOM)
SELECT FIPS_CNTRY, CNTRY_NAME, MDSYS.ST_MULTIPOLYGON(GEOM)
FROM ZTPD.COUNTRY_BOUNDARIES;

-- ZADANIE 3C
SELECT b.STGEOM.ST_GEOMETRYTYPE() AS TYP_OBIEKTU, COUNT(*) AS ILE
FROM MYST_COUNTRY_BOUNDARIES b
GROUP BY b.STGEOM.ST_GEOMETRYTYPE();

-- ZADANIE 3D
SELECT b.STGEOM.ST_ISSIMPLE()
FROM MYST_COUNTRY_BOUNDARIES b;

-- ZADANIE 4A
SELECT p.CNTRY_NAME, COUNT(*)
FROM MYST_COUNTRY_BOUNDARIES p
JOIN MYST_MAJOR_CITIES m
ON m.STGEOM.ST_WITHIN(p.STGEOM) = 1
GROUP BY p.CNTRY_NAME;

-- ZADANIE 4B
SELECT a.CNTRY_NAME AS A_NAME, b.CNTRY_NAME AS B_NAME
FROM MYST_COUNTRY_BOUNDARIES a
JOIN MYST_COUNTRY_BOUNDARIES b
ON a.STGEOM.ST_TOUCHES(b.STGEOM) = 1
WHERE b.CNTRY_NAME = 'Czech Republic';

-- ZADANIE 4C
SELECT DISTINCT c.CNTRY_NAME, r.NAME
FROM MYST_COUNTRY_BOUNDARIES c
JOIN ZTPD.RIVERS r
ON c.STGEOM.ST_CROSSES(MDSYS.ST_LINESTRING(r.GEOM)) = 1
WHERE c.CNTRY_NAME = 'Czech Republic';

-- ZADANIE 4D
SELECT SDO_GEOM.SDO_AREA(u.GEOM.GET_SDO_GEOM(), 0.005) AS POWIERZCHNIA
FROM (
SELECT a.STGEOM.ST_UNION(b.STGEOM) AS GEOM
FROM MYST_COUNTRY_BOUNDARIES a
JOIN MYST_COUNTRY_BOUNDARIES b
ON a.CNTRY_NAME = 'Czech Republic'
AND b.CNTRY_NAME = 'Slovakia'
) u;

-- ZADANIE 4E
SELECT x.OBIEKT, x.OBIEKT.ST_GEOMETRYTYPE() AS WEGRY_BEZ
FROM (SELECT w.STGEOM.ST_DIFFERENCE(MDSYS.ST_GEOMETRY(j.GEOM)) AS OBIEKT
    FROM MYST_COUNTRY_BOUNDARIES w
    JOIN ZTPD.WATER_BODIES j
    ON j.NAME = 'Balaton'
    WHERE w.CNTRY_NAME = 'Hungary'
) x;

-- ZADANIE 5A
SELECT b.CNTRY_NAME AS A_NAME, COUNT(*) AS ILE
FROM MYST_COUNTRY_BOUNDARIES b
JOIN MYST_MAJOR_CITIES c
ON SDO_WITHIN_DISTANCE(c.STGEOM, b.STGEOM, 'distance=100 unit=km') = 'TRUE'
WHERE b.CNTRY_NAME = 'Poland'
GROUP BY b.CNTRY_NAME;

