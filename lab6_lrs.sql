-- Zadanie 1A
CREATE TABLE S6_LRS (
    GEOM MDSYS.SDO_GEOMETRY
);

-- ZADANIE 1B
INSERT INTO S6_LRS (GEOM)
SELECT s.GEOM 
FROM ZTPD.STREETS_AND_RAILROADS s
WHERE SDO_WITHIN_DISTANCE(
    s.GEOM,
    (SELECT m.GEOM
    FROM ZTPD.MAJOR_CITIES m
    WHERE m.CITY_NAME = 'Koszalin'),
    'distance=10 unit=km'
)='TRUE';

-- ZADANIE 1C
SELECT SDO_GEOM.SDO_LENGTH(s.GEOM, 0.005, 'unit=km') AS DISTANCE,
    SDO_UTIL.GETNUMVERTICES(s.GEOM) AS ST_NUMPOINTS
FROM S6_LRS s;

-- ZADANIE 1D
UPDATE S6_LRS s
SET s.GEOM = SDO_LRS.CONVERT_TO_LRS_GEOM(s.GEOM, 0, SDO_GEOM.SDO_LENGTH(s.GEOM, 0.005, 'unit=km'));

-- ZADANIE 1E
INSERT INTO USER_SDO_GEOM_METADATA (TABLE_NAME, COLUMN_NAME, DIMINFO, SRID)
VALUES (
    'S6_LRS',
    'GEOM',
    MDSYS.SDO_DIM_ARRAY(
        MDSYS.SDO_DIM_ELEMENT('LONGITUDE', -180, 180, 0.05),
        MDSYS.SDO_DIM_ELEMENT('LATITUDE', -90, 90, 0.05),
        MDSYS.SDO_DIM_ELEMENT('M', 0, 277, 0.005)
    ),
    8307
);

COMMIT;

-- ZADANIE 1F
CREATE INDEX S6_LRS_IDX
ON S6_LRS(GEOM)
INDEXTYPE IS MDSYS.SPATIAL_INDEX_V2;

-- ZADANIE 2A
SELECT SDO_LRS.VALID_MEASURE(s.GEOM, 500) AS VALID_500
FROM S6_LRS s;

-- ZADANIE 2B
SELECT SDO_LRS.GEOM_SEGMENT_END_PT(s.GEOM) AS END_PT
FROM S6_LRS s;

-- ZADANIE 2C
SELECT SDO_LRS.LOCATE_PT(s.GEOM, 150) AS KM150
FROM S6_LRS s;

-- ZADANIE 2D
SELECT SDO_LRS.CLIP_GEOM_SEGMENT(s.GEOM, 120, 160) AS CLIPPED
FROM S6_LRS s;

-- ZADANIE 2E
SELECT SDO_LRS.GET_NEXT_SHAPE_PT(s.GEOM, m.GEOM) AS WJAZD_NA_S6
FROM S6_LRS s
CROSS JOIN ZTPD.MAJOR_CITIES m
WHERE m.CITY_NAME = 'Slupsk';

-- ZADANIE 2F
SELECT SDO_GEOM.SDO_LENGTH(SDO_LRS.OFFSET_GEOM_SEGMENT(s.GEOM, 50, 200, 50, 0.005, 'unit=m arc_tolerance=0.05'), 
        0.005, 'unit=km') AS KOSZT
FROM S6_LRS s;
